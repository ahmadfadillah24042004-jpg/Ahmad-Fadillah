#!/usr/bin/env python3
"""Scans images/, makes light WebP copies in images-web/ and writes data/manifest.js.
Original files are only read, never changed. Broken or empty files are skipped."""
import json, os, re
from pathlib import Path
from PIL import Image, ImageOps

ROOT = Path(__file__).resolve().parent.parent
SRC, OUT = ROOT / "images", ROOT / "images-web"
EXCLUDE = {"campaign/campaign-02.jpg"}          # paths inside images/ to hide from the site
EXT = {".jpg", ".jpeg", ".png", ".webp"}
SIZES = {"thumb": 800, "full": 1600}             # max width in px

slug = lambda s: re.sub(r"[^a-z0-9]+", "-", s.lower()).strip("-")
natural = lambda s: [int(t) if t.isdigit() else t for t in re.split(r"(\d+)", s.lower())]

gallery = {}
for folder, _, files in os.walk(SRC):
    rel_dir = Path(folder).relative_to(SRC).as_posix()
    if rel_dir == ".": continue
    items = []
    for f in sorted(files, key=lambda x: natural(x.strip())):
        p = Path(folder) / f
        rel = f"{rel_dir}/{f}"
        if p.suffix.lower() not in EXT or rel in EXCLUDE: continue
        try:
            im = ImageOps.exif_transpose(Image.open(p)).convert("RGB")
        except Exception:
            print("SKIPPED (broken or empty):", rel); continue
        w, h = im.size
        out_dir = OUT.joinpath(*[slug(x) for x in rel_dir.split("/")])
        out_dir.mkdir(parents=True, exist_ok=True)
        stem = slug(p.stem)
        entry = {"name": p.stem.strip(), "w": w, "h": h}
        for key, maxw in SIZES.items():
            dest = out_dir / f"{stem}-{key}.webp"
            if not dest.exists() or dest.stat().st_mtime < p.stat().st_mtime:
                tw = min(w, maxw)
                im.resize((tw, round(h * tw / w)), Image.LANCZOS).save(dest, "WEBP", quality=78, method=4)
            entry[key] = dest.relative_to(ROOT).as_posix()
        items.append(entry)
    if items: gallery[rel_dir] = items

(ROOT / "data").mkdir(exist_ok=True)
(ROOT / "data" / "manifest.js").write_text(
    "// Generated by scripts/build_gallery.py - do not edit by hand.\nwindow.GALLERY = "
    + json.dumps(gallery, indent=1) + ";\n", encoding="utf-8")
print({k: len(v) for k, v in gallery.items()})
